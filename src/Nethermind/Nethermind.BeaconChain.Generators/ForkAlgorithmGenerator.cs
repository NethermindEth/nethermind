using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Nethermind.BeaconChain.Generators;

/// <summary>Specializes fork algorithm templates into one concrete class per fork in the <c>BeaconForkTemplates</c> build property.</summary>
/// <remarks>
/// Fork differences are compile-time branches; emitted methods retain concrete state types and calls.
/// The property is a comma-separated list ordered by activation, <c>Fulu,Gloas</c> by default. The first fork keeps the
/// unprefixed names; each later fork prefixes or suffixes them with its name and defines its own upper-case symbol
/// and those of the forks between it and the first one.
/// </remarks>
[Generator]
public sealed class ForkAlgorithmGenerator : IIncrementalGenerator
{
    private static readonly string[] DefaultForks = { "Fulu", "Gloas" };

    private static readonly DiagnosticDescriptor InvalidTemplate = new("NMFORK001", "Invalid fork template",
        "{0}: {1}", "Generation", DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<string[]> forks = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.BeaconForkTemplates", out string? value) && !string.IsNullOrWhiteSpace(value)
                ? value.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries).Select(static fork => fork.Trim()).Where(static fork => fork.Length > 0).ToArray()
                : DefaultForks);
        context.RegisterSourceOutput(context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".forks.cs", StringComparison.Ordinal)).Combine(forks), static (output, input) =>
        {
            (AdditionalText file, string[] forks) = input;
            SourceText? text = file.GetText(output.CancellationToken);
            if (text is null) return;
            string name = Path.GetFileName(file.Path).Replace(".forks.cs", "");
            for (int index = 0; index < forks.Length; index++)
            {
                string? fork = index == 0 ? null : forks[index];
                CSharpParseOptions options = new(LanguageVersion.Preview,
                    preprocessorSymbols: forks.Skip(1).Take(index).Select(static later => later.ToUpperInvariant()).ToArray());
                SyntaxNode root = CSharpSyntaxTree.ParseText(text, options, file.Path, output.CancellationToken).GetRoot(output.CancellationToken);
                bool invalid = false;
                foreach (Diagnostic diagnostic in root.GetDiagnostics())
                {
                    if (diagnostic.Severity != DiagnosticSeverity.Error) continue;
                    output.ReportDiagnostic(Diagnostic.Create(InvalidTemplate, Location.None, file.Path, diagnostic.ToString()));
                    invalid = true;
                }
                if (invalid) continue;
                SyntaxNode specialized = new Specializer(name, forks[0], fork).Visit(root)!;
                output.AddSource(fork + name + ".forks.g.cs",
                    SourceText.From("// <auto-generated/>\n#nullable enable\n" + specialized.ToFullString(), Encoding.UTF8));
            }
        });
    }

    private sealed class Specializer(string name, string baseFork, string? fork) : CSharpSyntaxRewriter
    {
        public override SyntaxTrivia VisitTrivia(SyntaxTrivia trivia) =>
            trivia.IsDirective || trivia.IsKind(SyntaxKind.DisabledTextTrivia) ? default : base.VisitTrivia(trivia);

        public override SyntaxToken VisitToken(SyntaxToken token)
        {
            SyntaxToken visited = base.VisitToken(token);
            if (!token.IsKind(SyntaxKind.IdentifierToken)) return visited;
            string? replacement = token.ValueText switch
            {
                "ForkState" => "BeaconState" + (fork ?? baseFork),
                "ForkBlock" => "BeaconBlock" + fork,
                "ForkAttestation" => "Attestation" + fork,
                "ForkBody" => "BeaconBlockBody" + fork,
                "ForkAttesterSlashing" => "AttesterSlashing" + fork,
                "ForkIndexedAttestation" => "IndexedAttestation" + fork,
                "ForkSignatureSets" => fork + "SignatureSets",
                "ForkEpochProcessing" => fork + "EpochProcessing",
                _ when token.Parent is ClassDeclarationSyntax && token.ValueText == name => fork + name,
                _ => null,
            };
            return replacement is null ? visited : SyntaxFactory.Identifier(visited.LeadingTrivia, replacement, visited.TrailingTrivia);
        }
    }
}
