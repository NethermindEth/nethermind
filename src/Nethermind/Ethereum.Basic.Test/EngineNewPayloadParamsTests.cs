using System.Text.Json;
using Ethereum.Test.Base;
using NUnit.Framework;

namespace Ethereum.Basic.Test;

[TestFixture]
public class EngineNewPayloadParamsTests
{
    [TestCase("""["0xpayload",["0xh"],"0xroot",["0xreq"],["0x00","0x01","0x02","0x03","0x04","0x05","0x06","0x07","0x08","0x09","0x0a","0x0b","0x0c","0x0d","0x0e","0x0f","0x10"]]""", 5, 4, ExpectedResult = """["0xpayload",["0xh"],"0xroot",["0xreq"]]""", TestName = "Version below 6 passes through")]
    [TestCase("""["0xpayload",["0xh"],"0xroot",["0xreq"],[["0x00","0x10"],["0x01"],["0x02"],["0x03"],["0x04"],["0x05"],["0x06"],["0x07"],["0x08"],["0x09"],["0x0a"],["0x0b"],["0x0c"],["0x0d"],["0x0e"],["0x0f"]],[]]""", 6, 6, ExpectedResult = """["0xpayload",["0xh"],"0xroot",["0xreq"],[["0x00","0x10"],["0x01"],["0x02"],["0x03"],["0x04"],["0x05"],["0x06"],["0x07"],["0x08"],["0x09"],["0x0a"],["0x0b"],["0x0c"],["0x0d"],["0x0e"],["0x0f"]],[]]""", TestName = "Nested inclusion lists pass through")]
    [TestCase("""["0xpayload",["0xh"],"0xroot",["0xreq"],["0x00","0x01","0x02","0x03","0x04","0x05","0x06","0x07","0x08","0x09","0x0a","0x0b","0x0c","0x0d","0x0e","0x0f","0x10"]]""", 6, 6, ExpectedResult = """["0xpayload",["0xh"],"0xroot",["0xreq"],[["0x00","0x10"],["0x01"],["0x02"],["0x03"],["0x04"],["0x05"],["0x06"],["0x07"],["0x08"],["0x09"],["0x0a"],["0x0b"],["0x0c"],["0x0d"],["0x0e"],["0x0f"]],[]]""", TestName = "Flat list goes round-robin into 16 positions")]
    [TestCase("""["0xpayload",["0xh"],"0xroot",["0xreq"],[]]""", 6, 6, ExpectedResult = """["0xpayload",["0xh"],"0xroot",["0xreq"],[[],[],[],[],[],[],[],[],[],[],[],[],[],[],[],[]],[]]""", TestName = "Empty flat list gives 16 empty positions")]
    public string Flat_fixture_inclusion_list_is_split_across_committee_positions(string parameters, int payloadVersion, int paramCount)
    {
        using JsonDocument document = JsonDocument.Parse(parameters);
        JsonElement[] elements = [.. document.RootElement.EnumerateArray()];
        return "[" + string.Join(",", BlockchainTestBase.NewPayloadParams(elements, paramCount, payloadVersion)) + "]";
    }
}
