using static SszCSharp;

internal static class SszCodecEmitter
{
    internal static string GenerateSource(SszCodecDefinition definition)
    {
        SszDeclaration declaration = definition.Declaration;
        string kind = declaration.IsRecord ? (declaration.IsStruct ? "record struct" : "record class")
            : declaration.IsStruct ? "struct" : "class";
        string methods = Join(ScalarMethods(definition), SszCollectionEmitter.Emit(definition), SequenceDecode(declaration.TypeName));
        return $$"""
            // <auto-generated/>
            #nullable enable
            using System;
            using static global::Nethermind.Serialization.Ssz.Ssz;
            using static global::Nethermind.Serialization.Ssz.Merkleization.Merkle;

            {{(declaration.Namespace.Length == 0 ? string.Empty : $"namespace {declaration.Namespace};")}}

            partial {{kind}} {{declaration.TypeName}} : global::Nethermind.Serialization.Ssz.ISszCodec<{{declaration.TypeName}}> {{declaration.Constraints}}
            {
            {{Indent(methods)}}
            }
            """;
    }

    private static string ScalarMethods(SszCodecDefinition definition)
    {
        string name = definition.Declaration.TypeName;
        string argumentType = name + (definition.Declaration.IsStruct ? string.Empty : "?");
        string measure = SszEncodeEmitter.Measure(definition);
        int cachedLengthCount = SszEncodeEmitter.CachedLengthCount(definition);
        string measureForEncode = cachedLengthCount == 0 ? string.Empty : SszEncodeEmitter.Measure(definition, cacheLengths: true);
        string encode = SszEncodeEmitter.Encode(definition);
        string root = SszMerkleEmitter.Merkleize(definition);
        if (!definition.Declaration.IsStruct)
        {
            measure = Join("if (container is null) return 0;", measure);
            if (cachedLengthCount != 0) measureForEncode = Join("if (container is null) return 0;", measureForEncode);
            encode = Join("if (container is null) return;", encode);
            root = Join("if (container is null) { root = default; return; }", root);
        }
        string prepare = cachedLengthCount == 0 ? string.Empty
            : $"global::System.Span<int> __lengths = stackalloc int[{cachedLengthCount}];";
        string encodedLength = cachedLengthCount == 0 ? "GetLength(container)" : "MeasureForEncode(container, __lengths)";
        string lengthArgument = cachedLengthCount == 0 ? string.Empty : ", __lengths";
        string lengthParameter = cachedLengthCount == 0 ? string.Empty : ", global::System.ReadOnlySpan<int> __lengths";
        string cachedMeasureMethod = cachedLengthCount == 0 ? string.Empty : $$"""
            private static int MeasureForEncode({{argumentType}} container, global::System.Span<int> __lengths)
            {
            {{Indent(measureForEncode)}}
            }
            """;
        return $$"""
            public static int GetLength({{argumentType}} container)
            {
            {{Indent(measure)}}
            }

            public static byte[] Encode({{argumentType}} container)
            {
                {{prepare}}
                byte[] data = global::System.GC.AllocateUninitializedArray<byte>({{encodedLength}});
                EncodeCore(data, container{{lengthArgument}});
                return data;
            }

            public static void Encode(global::System.Span<byte> data, {{argumentType}} container)
            {
                {{prepare}}
                ValidateExactLength(data.Length, {{encodedLength}}, nameof({{name}}));
                EncodeCore(data, container{{lengthArgument}});
            }

            private static void EncodeCore(global::System.Span<byte> data, {{argumentType}} container{{lengthParameter}})
            {
            {{Indent(encode)}}
            }

            {{cachedMeasureMethod}}

            public static void Decode(global::System.ReadOnlySpan<byte> data, out {{name}} container)
            {
            {{Indent(SszDecodeEmitter.Decode(definition))}}
            }

            public static void Merkleize({{argumentType}} container, out global::Nethermind.Int256.UInt256 root)
            {
            {{Indent(root)}}
            }

            static void global::Nethermind.Serialization.Ssz.ISszCodec<{{name}}>.ReleaseDecoded({{name}} container)
            {
            {{Indent(SszOwnershipEmitter.Release(definition, "container"))}}
            }
            """;
    }

    private static string SequenceDecode(string name) => $$"""
        public static void Decode(global::System.Buffers.ReadOnlySequence<byte> data, out {{name}} container) =>
            global::Nethermind.Serialization.Ssz.Ssz.Decode(data, out container);
        """;
}
