internal static class SszCodecEmitter
{
    private const int UnboundedBitlistLimit = 0;

    internal static string GenerateSource(SszType type, string helperNamespace)
    {
        string declaration = $"partial {(type.IsStruct ? "struct" : "class")} {type.TypeReferenceName} : ISszCodec<{type.TypeReferenceName}>";
        if (!string.IsNullOrEmpty(type.TypeParameterConstraints))
        {
            declaration += " " + type.TypeParameterConstraints;
        }

        string methods = string.Join("\n\n", new[]
        {
            ScalarMethods(type),
            CollectionMethods(type),
            SequenceDecodeMethod(type.TypeReferenceName),
        });
        return $$"""
            // <auto-generated/>
            #nullable enable
            using Nethermind.Serialization.Ssz.Merkleization;
            using Nethermind.Serialization.Ssz;
            using static global::{{helperNamespace}}.SszCodecHelpers;
            {{UsingsBlock(type)}}

            {{(string.IsNullOrEmpty(type.Namespace) ? string.Empty : $"namespace {type.Namespace};")}}

            {{declaration}}
            {
            {{Indent(methods)}}
            }
            """;
    }

    private static string ScalarMethods(SszType type)
    {
        SszProperty[] members = type.Members ?? [];
        SszProperty[] variables = members.Where(member => member.IsVariable).ToArray();
        string argumentType = type.TypeReferenceName + (type.IsStruct ? string.Empty : "?");
        string getLength;
        string encode;
        string decode;
        string merkleize;
        if (type.IsSszListItself)
        {
            SszProperty member = members[0];
            string expression = $"container.{member.Name}";
            getLength = Join(ValidationStatement(type, member, expression), $"return checked({DynamicLength(member)});");
            encode = (RequiresNullGuard(member) ? $"if ({expression} is not null) " : string.Empty) + EncodeStatement("data", member, expression);
            decode = Join("container = new();", DecodeAndAssign(type, member, "data"));
            merkleize = Join(ValidationStatement(type, member, expression), MerkleizeRootAssignmentStatement(member, expression, "root"));
        }
        else if (type.Kind == Kind.CompatibleUnion)
        {
            getLength = UnionSwitch(type, member =>
            {
                string validation = ValidationStatement(type, member, $"container.{member.Name}");
                string length = member.IsVariable ? DynamicLength(member) : member.StaticLength.ToString();
                return Join(validation, $"return checked(1 + {length});");
            }, $"return ThrowInvalidSszData<int>(nameof({type.TypeReferenceName}), $\"unsupported union selector {{(byte)container.Selector}}.\");");
            encode = Join("data[0] = (byte)container.Selector;", UnionSwitch(type, member =>
            {
                string expression = $"container.{member.Name}";
                return NullClearingEncodeStatement("data.Slice(1)", member, expression, EncodeStatement("data.Slice(1)", member, expression)) + " break;";
            }, $"ThrowInvalidSszData(nameof({type.TypeReferenceName}), $\"unsupported union selector {{(byte)container.Selector}}.\"); break;"));
            decode = Join($"ValidateSszMinimumLength(data.Length, 1, nameof({type.TypeReferenceName}));", "container = new();",
                $"container.Selector = ({type.Selector!.Type.StaticMemberAccess})data[0];",
                UnionSwitch(type, member => DecodeAndAssign(type, member, "data.Slice(1)") + " break;",
                    $"ThrowInvalidSszData(nameof({type.TypeReferenceName}), $\"unsupported union selector {{data[0]}}.\"); break;"),
                $"ValidateSszExactLength(data.Length, GetLength(container), nameof({type.TypeReferenceName}));");
            merkleize = Join(UnionSwitch(type, member => Join(
                    ValidationStatement(type, member, $"container.{member.Name}"),
                    MerkleizeRootAssignmentStatement(member, $"container.{member.Name}", "root"), "break;"),
                $"root = ThrowInvalidSszData<UInt256>(nameof({type.TypeReferenceName}), $\"unsupported union selector {{(byte)container.Selector}}.\"); break;"),
                "Merkle.MixIn(ref root, (byte)container.Selector);");
        }
        else
        {
            string length = string.Join(" + ", new[] { type.StaticLength.ToString() }.Concat(variables.Select(member => DynamicLength(member))));
            getLength = Join(string.Join("\n", ValidationStatements(type, members, "container")), $"return checked({length});");
            encode = ContainerEncode(type, variables);
            decode = ContainerDecode(type, variables);
            merkleize = Join(string.Join("\n", ValidationStatements(type, members, "container")),
                type.Kind == Kind.ProgressiveContainer ? ProgressiveContainerMerkleizeBody(type) : ContainerMerkleize(type));
        }

        if (!type.IsStruct)
        {
            getLength = Join("if (container is null) return 0;", getLength);
            encode = Join("if (container is null) return;", encode);
            merkleize = Join("if (container is null) { root = default; return; }", merkleize);
        }

        return $$"""
            public static int GetLength({{argumentType}} container)
            {
            {{Indent(getLength)}}
            }

            public static byte[] Encode({{argumentType}} container)
            {
                byte[] data = global::System.GC.AllocateUninitializedArray<byte>(GetLength(container));
                EncodeCore(data, container);
                return data;
            }

            public static void Encode(Span<byte> data, {{argumentType}} container)
            {
                ValidateSszExactLength(data.Length, GetLength(container), nameof({{type.TypeReferenceName}}));
                EncodeCore(data, container);
            }

            private static void EncodeCore(Span<byte> data, {{argumentType}} container)
            {
            {{Indent(encode)}}
            }

            public static void Decode(ReadOnlySpan<byte> data, out {{type.TypeReferenceName}} container)
            {
            {{Indent(decode)}}
            }

            public static void Merkleize({{argumentType}} container, out UInt256 root)
            {
            {{Indent(merkleize)}}
            }
            """;
    }

    private static string ContainerEncode(SszType type, SszProperty[] variables)
    {
        List<string> lines = [];
        for (int index = 0; index < variables.Length; index++)
        {
            string offset = index == 0 ? type.StaticLength.ToString() : $"checked(offset{index} + {DynamicLength(variables[index - 1])})";
            lines.Add($"int offset{index + 1} = {offset};");
        }

        int staticOffset = 0;
        int variableIndex = 0;
        foreach (SszProperty member in type.Members!)
        {
            lines.Add(member.IsVariable
                ? $"EncodeSszOffset(data.Slice({staticOffset}, 4), offset{++variableIndex});"
                : StaticFieldEncodeStatement(member, staticOffset, "container"));
            staticOffset = checked(staticOffset + member.StaticLength);
        }

        for (int index = 0; index < variables.Length; index++)
        {
            SszProperty member = variables[index];
            string expression = $"container.{member.Name}";
            string end = index + 1 == variables.Length ? "data.Length" : $"offset{index + 2}";
            string target = $"data.Slice(offset{index + 1}, {end} - offset{index + 1})";
            lines.Add((RequiresNullGuard(member) ? $"if ({expression} is not null) " : string.Empty) + EncodeStatement(target, member, expression));
        }
        return string.Join("\n", lines);
    }

    private static string ContainerDecode(SszType type, SszProperty[] variables)
    {
        List<string> lines = [$"{(type.IsVariable ? "ValidateSszMinimumLength" : "ValidateSszExactLength")}(data.Length, {type.StaticLength}, nameof({type.TypeReferenceName}));"];
        int staticOffset = 0;
        int variableIndex = 0;
        foreach (SszProperty member in type.Members!)
        {
            if (member.IsVariable)
            {
                lines.Add($"int offset{++variableIndex} = DecodeSszOffset(data.Slice({staticOffset}, 4));");
            }
            staticOffset = checked(staticOffset + member.StaticLength);
        }

        if (variables.Length != 0)
        {
            string offsets = string.Join(", ", Enumerable.Range(1, variables.Length).Select(index => $"offset{index}"));
            lines.Add($"ValidateSszDynamicOffsets(data, {type.StaticLength}, nameof({type.TypeReferenceName}), [{offsets}]);");
        }
        lines.Add("container = new();");

        staticOffset = 0;
        foreach (SszProperty member in type.Members!)
        {
            if (!member.IsVariable)
            {
                lines.Add(DecodeAndAssign(type, member, $"data.Slice({staticOffset}, {member.StaticLength})"));
            }
            staticOffset = checked(staticOffset + member.StaticLength);
        }
        for (int index = 0; index < variables.Length; index++)
        {
            string end = index + 1 == variables.Length ? "data.Length" : $"offset{index + 2}";
            lines.Add(DecodeAndAssign(type, variables[index], $"data.Slice(offset{index + 1}, {end} - offset{index + 1})"));
        }
        return string.Join("\n", lines);
    }

    private static string ContainerMerkleize(SszType type) => Join(
        $"Span<UInt256> chunks = stackalloc UInt256[{MerkleDepth(type.Members!.Length) + 1}];",
        "Merkleizer merkleizer = new(chunks);",
        string.Join("\n", type.Members.Select(member => MerkleizeFeedStatement(member, $"container.{member.Name}"))),
        "merkleizer.CalculateRoot(out root);");

    private static int MerkleDepth(int count)
    {
        int depth = 0;
        for (int remaining = count - 1; remaining > 0; remaining >>= 1)
        {
            depth++;
        }
        return depth;
    }

    private static string UnionSwitch(SszType type, Func<SszProperty, string> body, string defaultBody)
    {
        string cases = string.Join("\n", type.CompatibleUnionMembers!.Select(member =>
            $"case {type.Selector!.Type.StaticMemberAccess}.{member.Name}:\n{Indent(body(member))}"));
        return $"switch (container.Selector)\n{{\n{Indent(cases)}\n    default:\n{Indent(defaultBody, 2)}\n}}";
    }

    private static string CollectionMethods(SszType type)
    {
        string name = type.TypeReferenceName;
        string nullableVariableGuard = !type.IsStruct && type.IsVariable && !type.IsSszListItself
            ? $"if (item is null) ThrowInvalidSszData(\"{name}[]\", \"null variable elements are not decodable.\");" : string.Empty;
        string getLength = type.IsVariable ? $$"""
            int length = checked(container.Length * 4);
            foreach ({{name}} item in container)
            {
                {{nullableVariableGuard}}
                length = checked(length + GetLength(item));
            }
            return length;
            """ : $"return checked(container.Length * {type.StaticLength});";
        string encode = type.IsVariable ? $$"""
            int offset = checked(items.Length * 4);
            int itemOffset = 0;
            foreach ({{name}} item in items)
            {
                {{nullableVariableGuard}}
                EncodeSszOffset(data.Slice(itemOffset, 4), offset);
                itemOffset += 4;
                int length = GetLength(item);
                EncodeCore(data.Slice(offset, length), item);
                offset = checked(offset + length);
            }
            """ : $$"""
            int offset = 0;
            foreach ({{name}} item in items)
            {
                {{(type.IsStruct ? string.Empty : $"if (item is null) data.Slice(offset, {type.StaticLength}).Clear(); else {{")}}
                _ = GetLength(item);
                EncodeCore(data.Slice(offset, {{type.StaticLength}}), item);
                {{(type.IsStruct ? string.Empty : "}")}}
                offset += {{type.StaticLength}};
            }
            """;

        string decode = CollectionDecode(type);
        string itemRoot = CollectionItemRoot(type);
        string zeroRootMethod = !type.IsStruct && !type.IsVariable ? $$"""
            private static void MerkleizeZeroEncoded(out UInt256 root)
            {
            {{Indent(ZeroTypeRootStatement(type, "root"))}}
            }
            """ : string.Empty;
        return $$"""
            public static int GetLength(ReadOnlySpan<{{name}}> container)
            {
            {{Indent(getLength)}}
            }

            public static byte[] Encode(ReadOnlySpan<{{name}}> items)
            {
                byte[] data = global::System.GC.AllocateUninitializedArray<byte>(GetLength(items));
                EncodeCore(data, items);
                return data;
            }

            public static void Encode(Span<byte> data, ReadOnlySpan<{{name}}> items)
            {
                ValidateSszExactLength(data.Length, GetLength(items), "{{name}}[]");
                EncodeCore(data, items);
            }

            private static void EncodeCore(Span<byte> data, ReadOnlySpan<{{name}}> items)
            {
            {{Indent(encode)}}
            }

            public static void Decode(ReadOnlySpan<byte> data, out {{name}}[] container)
            {
                if (data.IsEmpty)
                {
                    container = [];
                    return;
                }
            {{Indent(decode)}}
            }

            public static void MerkleizeVector(ReadOnlySpan<{{name}}> container, out UInt256 root)
            {
                MerkleizeCollection(container, (ulong)container.Length, out root);
            }

            public static void MerkleizeList(ReadOnlySpan<{{name}}> container, ulong limit, out UInt256 root)
            {
                MerkleizeCollection(container, limit, out root);
                Merkle.MixIn(ref root, container.Length);
            }

            private static void MerkleizeCollection(ReadOnlySpan<{{name}}> container, ulong limit, out UInt256 root)
            {
                if ((ulong)container.Length > limit)
                {
                    ThrowInvalidSszData("{{name}}[]", "element count exceeds the SSZ limit.");
                }
                Span<UInt256> chunks = stackalloc UInt256[Merkle.NextPowerOfTwoExponent(limit) + 1];
                Merkleizer merkleizer = new(chunks);
                for (int i = 0; i < container.Length; i++)
                {
            {{Indent(itemRoot, 2)}}
                    merkleizer.Feed(itemRoot);
                }
                merkleizer.CalculateRoot(out root);
            }

            public static void MerkleizeProgressiveList(ReadOnlySpan<{{name}}> container, out UInt256 root)
            {
                Span<UInt256> subtrees = stackalloc UInt256[17];
                Span<UInt256> scratch = stackalloc UInt256[33];
                int subtreeCount = 0;
                int offset = 0;
                ulong capacity = 1;
                while (offset < container.Length)
                {
                    int count = (int)Math.Min((ulong)(container.Length - offset), capacity);
                    Merkleizer merkleizer = new(scratch[..(Merkle.NextPowerOfTwoExponent(capacity) + 1)]);
                    for (int i = offset; i < offset + count; i++)
                    {
            {{Indent(itemRoot, 3)}}
                        merkleizer.Feed(itemRoot);
                    }
                    merkleizer.CalculateRoot(out subtrees[subtreeCount++]);
                    offset += count;
                    capacity *= 4;
                }
                MerkleizeProgressiveSubtrees(subtrees[..subtreeCount], out root);
                Merkle.MixIn(ref root, container.Length);
            }

            {{zeroRootMethod}}
            """;
    }

    private static string CollectionDecode(SszType type)
    {
        string name = type.TypeReferenceName;
        if (!type.IsVariable)
        {
            return $$"""
                ValidateSszMultipleOf(data.Length, {{type.StaticLength}}, "{{name}}[]");
                int length = data.Length / {{type.StaticLength}};
                container = new {{name}}[length];
                for (int index = 0, offset = 0; index < length; index++, offset += {{type.StaticLength}})
                {
                    Decode(data.Slice(offset, {{type.StaticLength}}), out container[index]);
                }
                """;
        }

        SszProperty? byteList = type.IsSszListItself && type.IsStruct && IsByteList(type.Members![0]) ? type.Members[0] : null;
        string decodeItem;
        if (byteList is null)
        {
            decodeItem = "Decode(data.Slice(offset, nextOffset - offset), out container[index]);";
        }
        else
        {
            string variableName = VarName(byteList.Name);
            decodeItem = Join($"byte[] {variableName} = DecodeSszByteList(data.Slice(offset, nextOffset - offset), {byteList.Limit}UL, nameof({name}), nameof({byteList.Name}));",
                $"container[index].{byteList.Name} = {DecodeAssignmentExpression(byteList, variableName, sourceIsArray: true)};");
        }

        return $$"""
            ValidateSszMinimumLength(data.Length, 4, "{{name}}[]");
            int firstOffset = DecodeSszOffset(data.Slice(0, 4));
            int length = ValidateSszVariableItemCount(data, firstOffset, "{{name}}[]");
            int offset = firstOffset;
            for (int index = 1; index < length; index++)
            {
                int nextOffset = DecodeSszOffset(data.Slice(index * 4, 4));
                ValidateSszNextOffset(data, offset, nextOffset, "{{name}}[]");
                offset = nextOffset;
            }
            container = new {{name}}[length];
            offset = firstOffset;
            for (int index = 0; index < length; index++)
            {
                int nextOffset = index + 1 == length ? data.Length : DecodeSszOffset(data.Slice((index + 1) * 4, 4));
            {{Indent(decodeItem)}}
                offset = nextOffset;
            }
            """;
    }

    private static string CollectionItemRoot(SszType type)
    {
        string nullItem = string.Empty;
        if (!type.IsStruct)
        {
            if (type.IsSszListItself)
            {
                return Join($"{type.TypeReferenceName} item = container[i];", "UInt256 itemRoot;",
                    $"if (item is null) {{ {MerkleizeEmptyCollectionRootStatement(type.Members![0], "itemRoot")} }} else {{ Merkleize(item, out itemRoot); }}");
            }
            else if (type.IsVariable)
            {
                nullItem = $"if (item is null) ThrowInvalidSszData(\"{type.TypeReferenceName}[]\", \"null variable elements are not decodable.\");";
            }
            else
            {
                return Join($"{type.TypeReferenceName} item = container[i];", "UInt256 itemRoot;",
                    "if (item is null) MerkleizeZeroEncoded(out itemRoot); else Merkleize(item, out itemRoot);");
            }
        }
        return Join($"{type.TypeReferenceName} item = container[i];", nullItem, "Merkleize(item, out UInt256 itemRoot);");
    }

    private static string SequenceDecodeMethod(string name) => $$"""
        public static void Decode(System.Buffers.ReadOnlySequence<byte> data, out {{name}} container)
        {
            if (data.IsSingleSegment)
            {
                Decode(data.FirstSpan, out container);
                return;
            }
            int length = checked((int)data.Length);
            byte[] rented = System.Buffers.ArrayPool<byte>.Shared.Rent(length);
            try
            {
                System.Buffers.BuffersExtensions.CopyTo(data, rented.AsSpan(0, length));
                Decode(rented.AsSpan(0, length), out container);
            }
            finally
            {
                System.Buffers.ArrayPool<byte>.Shared.Return(rented);
            }
        }
        """;

    private static string Join(params string[] statements) => string.Join("\n", statements.Where(statement => !string.IsNullOrEmpty(statement)));

    private static string Indent(string source, int depth = 1)
    {
        string prefix = new(' ', depth * 4);
        return string.Join("\n", source.Split('\n').Select(line => line.Length == 0 ? line : prefix + line));
    }

    private static string VarName(string name)
    {
        if (string.IsNullOrEmpty(name)) return name;

        string lowerCased = name.Substring(0, 1).ToLower() + name.Substring(1);

        return lowerCased == "data" || lowerCased == "container" || lowerCased.Contains("offset") ? $"_{lowerCased}" : lowerCased;
    }

    private static string ValidationStatement(SszType decl, SszProperty property, string expression)
    {
        string validation = property.Kind switch
        {
            Kind.Vector when property.Type.Name == "BitArray" => $"ValidateSszBitvectorLength({expression}, {property.Length}, nameof({decl.TypeReferenceName}), nameof({property.Name}));",
            Kind.Vector => $"ValidateSszVectorLength({SpanExpression(property, expression)}, {property.Length}, nameof({decl.TypeReferenceName}), nameof({property.Name}));",
            Kind.List => $"ValidateSszListLimit({SpanExpression(property, expression)}, {property.Limit}UL, nameof({decl.TypeReferenceName}), nameof({property.Name}));",
            Kind.BitVector => $"ValidateSszBitvectorLength({expression}, {property.Length}, nameof({decl.TypeReferenceName}), nameof({property.Name}));",
            Kind.BitList => $"ValidateSszBitlistLimit({expression}, {property.Limit}UL, nameof({decl.TypeReferenceName}), nameof({property.Name}));",
            _ => string.Empty,
        };

        if (!property.IsNullable)
        {
            return validation;
        }

        bool canEncodeNullAsDefault = CanEncodeNullAsDefault(property);

        if (!string.IsNullOrEmpty(validation) && canEncodeNullAsDefault)
        {
            return $"if ({expression} is not null) {validation}";
        }

        if (property.Kind == Kind.Vector)
        {
            return $"if ({expression} is null) throw new System.IO.InvalidDataException(\"Invalid SSZ value for {decl.TypeReferenceName}.{property.Name}: expected {property.Length} elements but found 0.\"); {validation}";
        }

        if (property.IsVariable && !canEncodeNullAsDefault)
        {
            return $"if ({expression} is null) throw new System.IO.InvalidDataException(\"Invalid SSZ value for {decl.TypeReferenceName}.{property.Name}: null variable fields are not decodable.\"); {validation}";
        }

        return validation;
    }

    private static bool CanEncodeNullAsDefault(SszProperty property) =>
        property.Kind switch
        {
            Kind.Vector => property.Type.Kind == Kind.Basic || property.Type.Name == "BitArray",
            Kind.BitVector or Kind.List or Kind.ProgressiveList or Kind.BitList or Kind.ProgressiveBitList => true,
            Kind.Basic when property.Type.HasCustomInlineCodec => true,
            _ => false,
        };

    private static string EncodeValueExpression(SszProperty property, string expression) =>
        property.Kind switch
        {
            Kind.BitList or Kind.ProgressiveBitList => $"{expression} ?? new BitArray(0)",
            _ when property.IsCollection && property.Type.Name != "BitArray" => SpanExpression(property, expression),
            _ => expression,
        };

    private static string EnumSpanExpression(SszProperty property, string expression) =>
        $"System.Runtime.InteropServices.MemoryMarshal.Cast<{property.Type.StaticMemberAccess}, {property.Type.EnumType!.StaticMemberAccess}>({SpanExpression(property, expression)})";

    private static string SpanExpression(SszProperty property, string expression) =>
        property.IsSpanLikeProperty ? expression
            : property.IsMemoryLikeProperty ? $"{expression}.Span"
            : property.IsArrayProperty ? $"{expression}.AsSpan()"
            : property.HasCollectionAsSpan ? $"{expression}{(property.IsNullable ? "!" : string.Empty)}.AsSpan()"
            : $"System.Runtime.InteropServices.CollectionsMarshal.AsSpan({expression})";

    private static IEnumerable<string> ValidationStatements(SszType decl, IEnumerable<SszProperty> properties, string expressionPrefix)
    {
        foreach (SszProperty property in properties)
        {
            string validation = ValidationStatement(decl, property, $"{expressionPrefix}.{property.Name}");
            if (!string.IsNullOrEmpty(validation))
            {
                yield return validation;
            }
        }
    }

    private static string StaticFieldEncodeStatement(SszProperty property, int staticOffset, string containerExpr)
    {
        string destSpan = $"data.Slice({staticOffset}, {property.StaticLength})";
        string valueExpr = $"{containerExpr}.{property.Name}";
        string encodedValueExpr = EncodeValueExpression(property, valueExpr);

        string statement;
        if (property.Kind != Kind.Basic)
        {
            statement = EncodeStatement(destSpan, property, valueExpr);
        }
        else if (property.Type.EnumType is { HasCustomInlineCodec: true } enumType)
        {
            statement = enumType.CustomEncodeTemplate!
                .Replace("{0}", destSpan)
                .Replace("{1}", $"({enumType.StaticMemberAccess}){encodedValueExpr}");
        }
        else if (property.Type.HasCustomInlineCodec)
        {
            statement = property.Type.CustomEncodeTemplate!
                .Replace("{0}", destSpan)
                .Replace("{1}", encodedValueExpr);
        }
        else
        {
            statement = property.HandledByStd
                ? $"Nethermind.Serialization.Ssz.Ssz.Encode({destSpan}, {encodedValueExpr});"
                : $"{property.Type.StaticMemberAccess}.Encode({destSpan}, {encodedValueExpr});";
        }

        // Reference-typed static fields encode as zeros when null.
        return NullClearingEncodeStatement(destSpan, property, valueExpr, statement);
    }

    private static string NullClearingEncodeStatement(string target, SszProperty property, string valueExpr, string statement) =>
        property.IsNullable || property.IsReferenceType ? $"if ({valueExpr} is null) {target}.Clear(); else {statement}" : statement;

    private static bool IsByteList(SszProperty property) =>
        property.Kind == Kind.List && (property.IsArrayProperty || property.IsMemoryLikeProperty) && property.Type is { Name: nameof(Byte), IsSszBasicType: true };

    private static bool IsByteVector(SszProperty property) =>
        property.Kind == Kind.Vector && (property.IsArrayProperty || property.IsMemoryLikeProperty) && property.Type is { Name: nameof(Byte), IsSszBasicType: true };

    private static string DecodeAndAssign(SszType decl, SszProperty property, string sliceExpression)
    {
        string variableName = VarName(property.Name);

        if (property.Type.EnumType is { HasCustomInlineCodec: true } enumType && property.Kind == Kind.Basic)
        {
            string decodeStatement = $"container.{property.Name} = ({property.Type.StaticMemberAccess}){enumType.CustomDecodeMethod}({sliceExpression});";
            string validation = ValidationStatement(decl, property, $"container.{property.Name}");
            return string.IsNullOrEmpty(validation) ? decodeStatement : $"{decodeStatement} {validation}";
        }

        if (property.Type.HasCustomInlineCodec && property.Kind == Kind.Basic)
        {
            string decodeStatement = property.Type.CustomDecodeTemplate!
                .Replace("{0}", sliceExpression)
                .Replace("{1}", $"container.{property.Name}");
            string validation = ValidationStatement(decl, property, $"container.{property.Name}");
            return string.IsNullOrEmpty(validation) ? decodeStatement : $"{decodeStatement} {validation}";
        }

        if (IsByteList(property))
        {
            string assignment = DecodeAssignmentExpression(property, variableName, sourceIsArray: true);
            return $"{{ byte[] {variableName} = DecodeSszByteList({sliceExpression}, {property.Limit}UL, nameof({decl.TypeReferenceName}), nameof({property.Name})); container.{property.Name} = {assignment}; }}";
        }

        if (IsByteVector(property))
        {
            string assignment = DecodeAssignmentExpression(property, variableName, sourceIsArray: true);
            return $"{{ byte[] {variableName} = DecodeSszByteVector({sliceExpression}, {property.Length}, nameof({decl.TypeReferenceName}), nameof({property.Name})); container.{property.Name} = {assignment}; }}";
        }

        SszType converter = property.Type.EnumType ?? property.Type;
        if ((property.Kind is Kind.Vector or Kind.List or Kind.ProgressiveList) && property.Type.Kind == Kind.Basic && converter.HasCustomInlineCodec)
        {
            int itemSize = property.Type.StaticLength;
            string lengthGuard = property.Kind == Kind.Vector
                ? $"ValidateSszExactLength({sliceExpression}.Length, {checked(property.Length!.Value * itemSize)}, \"{decl.TypeReferenceName}.{property.Name}\");"
                : $"ValidateSszMultipleOf({sliceExpression}.Length, {itemSize}, \"{decl.TypeReferenceName}.{property.Name}\");";
            string countDeclaration = property.Kind == Kind.Vector ? string.Empty : $"int __count = {sliceExpression}.Length / {itemSize};";
            string countExpression = property.Kind == Kind.Vector ? property.Length!.Value.ToString() : "__count";
            string limitGuard = property.Kind == Kind.List && property.Limit is <= int.MaxValue
                ? $"if (__count > {property.Limit.Value}) throw new System.IO.InvalidDataException($\"{decl.TypeReferenceName}.{property.Name}: list count {{__count}} exceeds SSZ limit {property.Limit.Value}\");"
                : string.Empty;
            string elementType = property.Type.StaticMemberAccess;
            string allocation = property.IsListProperty
                ? $"System.Collections.Generic.List<{elementType}> {variableName} = new({countExpression}); System.Runtime.InteropServices.CollectionsMarshal.SetCount({variableName}, {countExpression});"
                : $"{elementType}[] {variableName} = new {elementType}[{countExpression}];";
            string destination = property.IsListProperty
                ? $"System.Runtime.InteropServices.CollectionsMarshal.AsSpan({variableName})"
                : $"{variableName}.AsSpan()";
            if (property.Type.EnumType is not null)
            {
                destination = $"System.Runtime.InteropServices.MemoryMarshal.Cast<{elementType}, {converter.StaticMemberAccess}>({destination})";
            }
            string assignment = property.IsListProperty ? variableName : DecodeAssignmentExpression(property, variableName, sourceIsArray: true);
            return $"{{ {lengthGuard} {countDeclaration} {limitGuard} {allocation} {converter.CustomDecodeMethod}({sliceExpression}, {destination}); container.{property.Name} = {assignment}; }}";
        }

        string outType = property.Kind switch
        {
            Kind.BitVector or Kind.BitList or Kind.ProgressiveBitList => "BitArray",
            _ when property.IsCollection => property.HandledByStd ? $"ReadOnlySpan<{property.Type.StaticMemberAccess}>" : $"{property.Type.StaticMemberAccess}[]",
            _ => property.Type.StaticMemberAccess,
        };

        string decode = property.Kind switch
        {
            Kind.BitVector => $"DecodeSszBitVector({sliceExpression}, {property.Length}, out {outType} {variableName});",
            Kind.BitList or Kind.ProgressiveBitList => $"DecodeSszBitList({sliceExpression}, {property.Limit ?? ulong.MaxValue}UL, nameof({decl.TypeReferenceName}), out {outType} {variableName});",
            _ when property.HandledByStd => $"Nethermind.Serialization.Ssz.Ssz.Decode({sliceExpression}, out {outType} {variableName});",
            _ => $"{property.Type.StaticMemberAccess}.Decode({sliceExpression}, out {outType} {variableName});",
        };

        string assignment2 = $"container.{property.Name} = {DecodeAssignmentExpression(property, variableName, !property.HandledByStd)};";
        string validation2 = ValidationStatement(decl, property, $"container.{property.Name}");

        string preAllocationListGuard = string.Empty;
        // No guard for limits beyond int.MaxValue: an int-typed count can never exceed them
        if (property.Kind == Kind.List && property.Limit is <= int.MaxValue && !property.HandledByStd)
        {
            preAllocationListGuard = property.Type.IsVariable
                ? $"if ({sliceExpression}.Length >= {SszType.PointerLength}) {{ int __firstOffset = DecodeSszOffset({sliceExpression}.Slice(0, {SszType.PointerLength})); int __preCount = __firstOffset / {SszType.PointerLength}; if (__preCount > {property.Limit.Value}) throw new System.IO.InvalidDataException($\"{decl.TypeReferenceName}.{property.Name}: list count {{__preCount}} exceeds SSZ limit {property.Limit.Value}\"); }}"
                : $"{{ int __preCount = {sliceExpression}.Length / {property.Type.StaticLength}; if (__preCount > {property.Limit.Value}) throw new System.IO.InvalidDataException($\"{decl.TypeReferenceName}.{property.Name}: list count {{__preCount}} exceeds SSZ limit {property.Limit.Value}\"); }}";
        }

        List<string> statements = [];
        if (!string.IsNullOrEmpty(preAllocationListGuard))
        {
            statements.Add(preAllocationListGuard);
        }
        statements.Add(decode);
        statements.Add(assignment2);
        if (!string.IsNullOrEmpty(validation2))
        {
            statements.Add(validation2);
        }
        return string.Join(" ", statements);
    }

    private static string DecodeAssignmentExpression(SszProperty property, string variableName, bool sourceIsArray) =>
        property switch
        {
            { IsReadOnlySpanProperty: true } => variableName,
            { IsReadOnlyMemoryProperty: true } => sourceIsArray ? variableName : $"{variableName}.ToArray()",
            { IsSpanLikeProperty: true, HandledByStd: true } => sourceIsArray ? variableName : $"{variableName}.ToArray()",
            { IsSpanLikeProperty: true } => variableName,
            { IsMemoryLikeProperty: true } => sourceIsArray ? variableName : $"{variableName}.ToArray()",
            { IsCollection: true, CanConstructCollectionFromReadOnlySpan: true, CollectionTypeReferenceName: not null } => $"new {property.CollectionTypeReferenceName}({variableName})",
            { IsCollection: true, IsArrayProperty: true } => sourceIsArray ? variableName : $"[ ..{variableName}]",
            { IsCollection: true } => $"[ ..{variableName}]",
            _ => variableName,
        };

    private static string ConverterMerkleizeStatement(SszProperty property, string expression, string rootName) =>
        $"MerkleizeWithConverter({expression}, {property.Type.CustomFeedMethod}, out {rootName});";

    private static string ConverterFeedStatement(SszProperty property, string expression) =>
        property.Type.CustomFeedTemplate!
            .Replace("{0}", "merkleizer")
            .Replace("{1}", expression);

    private static string MerkleizeRootStatement(SszProperty property, string expression, string rootName) =>
        property.Kind switch
        {
            Kind.Basic when property.Type.EnumType?.CustomFeedMethod is not null => $"MerkleizeWithConverter(({property.Type.EnumType.StaticMemberAccess}){expression}, {property.Type.EnumType.CustomFeedMethod}, out {rootName});",
            Kind.Basic when property.Type.CustomFeedMethod is not null => ConverterMerkleizeStatement(property, expression, rootName),
            Kind.Basic => $"Merkle.Merkleize(out {rootName}, {expression});",
            Kind.BitVector => $"Merkle.Merkleize(out {rootName}, {expression}!);",
            Kind.BitList => $"Merkle.Merkleize(out {rootName}, {expression} ?? new BitArray(0), {property.Limit}UL);",
            Kind.ProgressiveBitList => $"MerkleizeProgressiveBitList({expression}, out {rootName});",
            Kind.Vector when property.Type.Kind == Kind.Basic && property.Type.EnumType is { HasCustomInlineCodec: true, IsSszBasicType: true } enumType => $"MerkleizeBasicVectorWithConverter<{enumType.StaticMemberAccess}>({EnumSpanExpression(property, expression)}, {enumType.StaticLength}, {property.Length}, {enumType.CustomEncodeMethod}, out {rootName});",
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.EnumType is { HasCustomInlineCodec: true, IsSszBasicType: true } enumType => $"MerkleizeBasicListWithConverter<{enumType.StaticMemberAccess}>({EnumSpanExpression(property, expression)}, {enumType.StaticLength}, {property.Limit}UL, {enumType.CustomEncodeMethod}, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.EnumType is { HasCustomInlineCodec: true, IsSszBasicType: true } enumType => $"MerkleizeProgressiveBasicListWithConverter<{enumType.StaticMemberAccess}>({EnumSpanExpression(property, expression)}, {enumType.StaticLength}, {enumType.CustomEncodeMethod}, out {rootName});",
            Kind.Vector when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec && property.Type.IsSszBasicType => $"MerkleizeBasicVectorWithConverter<{property.Type.StaticMemberAccess}>({SpanExpression(property, expression)}, {property.Type.StaticLength}, {property.Length}, {property.Type.CustomEncodeMethod}, out {rootName});",
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec && property.Type.IsSszBasicType => $"MerkleizeBasicListWithConverter<{property.Type.StaticMemberAccess}>({SpanExpression(property, expression)}, {property.Type.StaticLength}, {property.Limit}UL, {property.Type.CustomEncodeMethod}, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec && property.Type.IsSszBasicType => $"MerkleizeProgressiveBasicListWithConverter<{property.Type.StaticMemberAccess}>({SpanExpression(property, expression)}, {property.Type.StaticLength}, {property.Type.CustomEncodeMethod}, out {rootName});",
            Kind.Vector when property.Type.Kind == Kind.Basic && property.Type.IsSszBasicType => $"MerkleizeBasicVector({SpanExpression(property, expression)}, {property.Type.StaticLength}, {property.Length}, out {rootName});",
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.IsSszBasicType => $"MerkleizeBasicList({SpanExpression(property, expression)}, {property.Type.StaticLength}, {property.Limit}UL, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.IsSszBasicType => $"MerkleizeProgressiveBasicList({SpanExpression(property, expression)}, out {rootName});",
            Kind.Vector when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec => $"MerkleizeCompositeVectorWithConverter({SpanExpression(property, expression)}, {property.Length}, {property.Type.CustomFeedMethod}, out {rootName});",
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec => $"MerkleizeCompositeListWithConverter({SpanExpression(property, expression)}, {property.Limit}UL, {property.Type.CustomFeedMethod}, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec => $"MerkleizeCompositeProgressiveListWithConverter({SpanExpression(property, expression)}, {property.Type.CustomFeedMethod}, out {rootName});",
            Kind.Vector => $"{property.Type.StaticMemberAccess}.MerkleizeVector({SpanExpression(property, expression)}, out {rootName});",
            Kind.List => $"{property.Type.StaticMemberAccess}.MerkleizeList({SpanExpression(property, expression)}, {property.Limit}UL, out {rootName});",
            Kind.ProgressiveList => $"{property.Type.StaticMemberAccess}.MerkleizeProgressiveList({SpanExpression(property, expression)}, out {rootName});",
            _ => $"{property.Type.StaticMemberAccess}.Merkleize({expression}, out {rootName});",
        };

    private static string MerkleizeEmptyCollectionRootStatement(SszProperty property, string rootName) =>
        property.Kind switch
        {
            Kind.Vector or Kind.BitVector => ZeroPropertyRootStatement(property, rootName),
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.EnumType is { HasCustomInlineCodec: true, IsSszBasicType: true } enumType => $"MerkleizeBasicListWithConverter<{enumType.StaticMemberAccess}>(System.Runtime.InteropServices.MemoryMarshal.Cast<{property.Type.StaticMemberAccess}, {enumType.StaticMemberAccess}>(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty), {enumType.StaticLength}, {property.Limit}UL, {enumType.CustomEncodeMethod}, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.EnumType is { HasCustomInlineCodec: true, IsSszBasicType: true } enumType => $"MerkleizeProgressiveBasicListWithConverter<{enumType.StaticMemberAccess}>(System.Runtime.InteropServices.MemoryMarshal.Cast<{property.Type.StaticMemberAccess}, {enumType.StaticMemberAccess}>(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty), {enumType.StaticLength}, {enumType.CustomEncodeMethod}, out {rootName});",
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec && property.Type.IsSszBasicType => $"MerkleizeBasicListWithConverter<{property.Type.StaticMemberAccess}>(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, {property.Type.StaticLength}, {property.Limit}UL, {property.Type.CustomEncodeMethod}, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec && property.Type.IsSszBasicType => $"MerkleizeProgressiveBasicListWithConverter<{property.Type.StaticMemberAccess}>(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, {property.Type.StaticLength}, {property.Type.CustomEncodeMethod}, out {rootName});",
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.IsSszBasicType => $"MerkleizeBasicList(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, {property.Type.StaticLength}, {property.Limit}UL, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.IsSszBasicType => $"MerkleizeProgressiveBasicList(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, out {rootName});",
            Kind.List when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec => $"MerkleizeCompositeListWithConverter(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, {property.Limit}UL, {property.Type.CustomFeedMethod}, out {rootName});",
            Kind.ProgressiveList when property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec => $"MerkleizeCompositeProgressiveListWithConverter(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, {property.Type.CustomFeedMethod}, out {rootName});",
            Kind.List => $"{property.Type.StaticMemberAccess}.MerkleizeList(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, {property.Limit}UL, out {rootName});",
            Kind.ProgressiveList => $"{property.Type.StaticMemberAccess}.MerkleizeProgressiveList(ReadOnlySpan<{property.Type.StaticMemberAccess}>.Empty, out {rootName});",
            _ => throw new InvalidOperationException($"Cannot merkleize an empty {property.Kind} collection."),
        };

    private static string ZeroTypeRootStatement(SszType type, string rootName)
    {
        int localIndex = 0;
        return ZeroTypeRootStatement(type, rootName, ref localIndex);
    }

    private static string ZeroPropertyRootStatement(SszProperty property, string rootName)
    {
        int localIndex = 0;
        return ZeroPropertyRootStatement(property, rootName, ref localIndex);
    }

    private static string ZeroPackedRootStatement(int byteLength, string rootName) =>
        $"Merkle.Merkleize(out {rootName}, ReadOnlySpan<byte>.Empty, {((ulong)byteLength + 31) / 32}UL);";

    private static string ZeroPropertyRootStatement(SszProperty property, string rootName, ref int localIndex)
    {
        if (property.Kind == Kind.BitVector || (property.Kind == Kind.Vector && property.Type.IsSszBasicType))
        {
            return ZeroPackedRootStatement(property.StaticLength, rootName);
        }

        if (property.Kind != Kind.Vector)
        {
            return ZeroTypeRootStatement(property.Type, rootName, ref localIndex);
        }

        string itemRoot = $"__sszZeroRoot{localIndex++}";
        string merkleizer = $"__sszZeroTree{localIndex++}";
        string index = $"__sszZeroIndex{localIndex++}";
        return Join("{", $"UInt256 {itemRoot};", ZeroTypeRootStatement(property.Type, itemRoot, ref localIndex),
            $"Merkleizer {merkleizer} = new(stackalloc UInt256[{MerkleDepth(property.Length!.Value) + 1}]);",
            $"for (int {index} = 0; {index} < {property.Length}; {index}++) {merkleizer}.Feed({itemRoot});",
            $"{merkleizer}.CalculateRoot(out {rootName});", "}");
    }

    private static string ZeroTypeRootStatement(SszType type, string rootName, ref int localIndex)
    {
        if (type.Kind == Kind.Basic)
        {
            return ZeroPackedRootStatement(type.StaticLength, rootName);
        }

        if (type.Kind == Kind.ProgressiveContainer)
        {
            string roots = $"__sszZeroFields{localIndex++}";
            List<string> lines = ["{", $"Span<UInt256> {roots} = stackalloc UInt256[{type.ActiveFieldsBitLength}];", $"{roots}.Clear();"];
            foreach (SszProperty member in type.Members!)
            {
                lines.Add(ZeroPropertyRootStatement(member, $"{roots}[{member.FieldIndex}]", ref localIndex));
            }
            lines.Add($"Merkle.MerkleizeProgressive(out {rootName}, {roots});");
            lines.Add($"Merkle.MixInActiveFields(ref {rootName}, [{string.Join(", ", type.ActiveFieldsBytes ?? [])}]);");
            lines.Add("}");
            return string.Join("\n", lines);
        }

        string merkleizer = $"__sszZeroTree{localIndex++}";
        List<string> statements = ["{", $"Merkleizer {merkleizer} = new(stackalloc UInt256[{MerkleDepth(type.Members!.Length) + 1}]);"];
        foreach (SszProperty member in type.Members)
        {
            string fieldRoot = $"__sszZeroRoot{localIndex++}";
            statements.Add($"UInt256 {fieldRoot};");
            statements.Add(ZeroPropertyRootStatement(member, fieldRoot, ref localIndex));
            statements.Add($"{merkleizer}.Feed({fieldRoot});");
        }
        statements.Add($"{merkleizer}.CalculateRoot(out {rootName});");
        statements.Add("}");
        return string.Join("\n", statements);
    }

    private static string MerkleizeRootAssignmentStatement(SszProperty property, string expression, string rootName)
    {
        string body = MerkleizeRootStatement(property, expression, rootName);
        if ((!property.IsNullable && !(property.IsReferenceType && !property.IsVariable)) || property.IsSpanLikeProperty || property.Kind is Kind.BitList or Kind.ProgressiveBitList)
        {
            return body;
        }

        if (property.Kind is (Kind.Vector or Kind.BitVector or Kind.List or Kind.ProgressiveList) && CanEncodeNullAsDefault(property))
        {
            return $"if ({expression} is null) {{ {MerkleizeEmptyCollectionRootStatement(property, rootName)} }} else {{ {body} }}";
        }

        if (property.Kind == Kind.Basic && property.Type.HasCustomInlineCodec)
        {
            return $"if ({expression} is null) {{ {ZeroPackedRootStatement(property.Type.StaticLength, rootName)} }} else {{ {body} }}";
        }

        if (!property.IsVariable && property.Kind != Kind.Basic)
        {
            return $"if ({expression} is null) {{ {ZeroPropertyRootStatement(property, rootName)} }} else {{ {body} }}";
        }

        return $"if ({expression} is null) {{ {rootName} = default; }} else {{ {body} }}";
    }

    private static string MerkleizeFeedStatement(SszProperty property, string expression)
    {
        if (property.Kind == Kind.Basic && property.Type.CustomFeedTemplate is not null && !property.IsNullable && !property.IsReferenceType)
        {
            return ConverterFeedStatement(property, expression);
        }

        string rootName = VarName(property.Name) + "Root";
        return $"UInt256 {rootName}; {MerkleizeRootAssignmentStatement(property, expression, rootName)} merkleizer.Feed({rootName});";
    }

    private static string DynamicLength(SszProperty m)
    {
        if ((m.Kind & (Kind.Collection | Kind.BitList | Kind.ProgressiveBitList)) != Kind.None && m.Type.Kind == Kind.Basic)
        {
            string length = m.Kind is Kind.BitList or Kind.ProgressiveBitList
                ? $"(container.{m.Name} is not null ? container.{m.Name}.Length / 8 + 1 : 1)"
                : $"({m.Type.StaticLength} * {SpanExpression(m, $"container.{m.Name}")}.Length)";
            return m.IsNullable && (m.Kind is Kind.List or Kind.ProgressiveList) && CanEncodeNullAsDefault(m)
                ? $"(container.{m.Name} is null ? 0 : {length})"
                : length;
        }

        string call = m.IsCollection
            ? $"{m.Type.StaticMemberAccess}.GetLength({SpanExpression(m, $"container.{m.Name}")})"
            : $"{m.Type.StaticMemberAccess}.GetLength(container.{m.Name})";

        return m.IsNullable ? $"(container.{m.Name} is null ? 0 : {call})" : call;
    }

    private static string ProgressiveContainerMerkleizeBody(SszType decl)
    {
        string activeFields = $"[{string.Join(", ", decl.ActiveFieldsBytes ?? [])}]";
        IEnumerable<string> memberRoots = decl.Members!.Select(m =>
            MerkleizeRootAssignmentStatement(m, $"container.{m.Name}", $"subRoots[{m.FieldIndex}]"));
        bool useStack = decl.ActiveFieldsBitLength <= 32;

        return string.Join("\n",
        [
            useStack
                ? $"Span<UInt256> subRoots = stackalloc UInt256[{decl.ActiveFieldsBitLength}];"
                : $"UInt256[] rented = System.Buffers.ArrayPool<UInt256>.Shared.Rent({decl.ActiveFieldsBitLength});\nSpan<UInt256> subRoots = rented.AsSpan(0, {decl.ActiveFieldsBitLength});",
            ..(useStack ? Array.Empty<string>() : ["try", "{"]),
            "subRoots.Clear();",
            ..memberRoots,
            "Merkle.MerkleizeProgressive(out root, subRoots);",
            ..(useStack ? Array.Empty<string>() : ["}", "finally", "{", "System.Buffers.ArrayPool<UInt256>.Shared.Return(rented);", "}"]),
            $"Merkle.MixInActiveFields(ref root, {activeFields});",
        ]);
    }

    private static string EncodeStatement(string target, SszProperty property, string expression)
    {
        if (property.Kind == Kind.Basic && property.Type.HasCustomInlineCodec)
        {
            return property.Type.CustomEncodeTemplate!
                .Replace("{0}", target)
                .Replace("{1}", EncodeValueExpression(property, expression));
        }

        if ((property.Kind is Kind.List or Kind.Vector or Kind.ProgressiveList) && property.Type.Kind == Kind.Basic && property.Type.HasCustomInlineCodec)
        {
            return $"{property.Type.CustomEncodeMethod}({target}, {SpanExpression(property, expression)});";
        }

        if ((property.Kind is Kind.List or Kind.Vector or Kind.ProgressiveList) && property.Type.Kind == Kind.Basic && property.Type.EnumType is { HasCustomInlineCodec: true } enumType)
        {
            return $"{enumType.CustomEncodeMethod}({target}, {EnumSpanExpression(property, expression)});";
        }

        string arguments = $"{target}, {EncodeValueExpression(property, expression)}";
        if (property.Kind == Kind.BitList)
        {
            // The Encode limit parameter is int-typed; bitlist limits beyond int.MaxValue are
            // rejected at parse time (a BitArray cannot exceed int.MaxValue bits), so this fits.
            arguments += $", {property.Limit!.Value}";
        }
        else if (property.Kind == Kind.ProgressiveBitList)
        {
            arguments += $", {UnboundedBitlistLimit}";
        }

        return $"{(property.HandledByStd ? "Nethermind.Serialization.Ssz.Ssz.Encode" : $"{property.Type.StaticMemberAccess}.Encode")}({arguments});";
    }

    private static bool RequiresNullGuard(SszProperty property)
    {
        if (property.IsSpanLikeProperty || property.IsMemoryLikeProperty || property.Kind is Kind.BitList or Kind.ProgressiveBitList)
        {
            return false;
        }

        return (property.IsNullable && CanEncodeNullAsDefault(property)) || !property.Type.IsStruct;
    }

    private static string UsingsBlock(SszType decl) =>
        string.Join("\n", ReferencedTypes(decl)
            .SelectMany(GeneratedNamespaces)
            .Concat(decl.TypeParameterConstraintNamespaces)
            .Append("Nethermind.Int256")
            .Append("System")
            .Distinct()
            .OrderBy(x => x)
            .Where(x => !string.IsNullOrEmpty(x) && x != decl.Namespace && x != "Nethermind.Serialization.Ssz")
            .Select(n => $"using {n};"));

    private static IEnumerable<SszType> ReferencedTypes(SszType type)
    {
        HashSet<SszType> visited = [];
        Stack<SszType> pending = new();
        pending.Push(type);

        while (pending.Count > 0)
        {
            SszType current = pending.Pop();
            if (!visited.Add(current))
            {
                continue;
            }

            yield return current;

            if (current.EnumType is not null)
            {
                pending.Push(current.EnumType);
            }

            if (current.Members is null)
            {
                continue;
            }

            for (int i = 0; i < current.Members.Length; i++)
            {
                pending.Push(current.Members[i].Type);
            }
        }
    }

    private static IEnumerable<string> GeneratedNamespaces(SszType type)
    {
        string? typeNamespace = type.Namespace;
        if (typeNamespace is { Length: > 0 })
        {
            yield return typeNamespace;
        }

        foreach (string namespaceName in type.AdditionalNamespaces)
        {
            yield return namespaceName;
        }
    }
