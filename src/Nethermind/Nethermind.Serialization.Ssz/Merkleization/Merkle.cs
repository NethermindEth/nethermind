    public static UInt256[] ZeroHashes => ZeroHashesArray.Instance;

    /// <summary>Reads the zero-subtree hash for <paramref name="level"/> straight from constant data.</summary>
    /// <remarks>
    /// The chain is baked in rather than computed in a static constructor: an uninterpretable
    /// constructor would leave the whole type lazily initialized, putting an initialization check
    /// (a lock and thread-static access on NativeAOT) on every static call into this class -
    /// measurably hot on the zkVM guest, where merkleization dominates witness loading.
    /// </remarks>
    internal static UInt256 ZeroHash(int level) => MemoryMarshal.Read<UInt256>(ZeroHashData.Slice(level * 32, 32));

