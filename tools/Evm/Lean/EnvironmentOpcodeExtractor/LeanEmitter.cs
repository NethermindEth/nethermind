using System.Globalization;
using System.Text;

namespace Nethermind.Evm.Lean.EnvironmentOpcodeExtractor;

internal static class LeanEmitter
{
    private static readonly UTF8Encoding Utf8WithoutBom = new(false);

    internal static byte[] Emit(IrDocument document, string irHash)
    {
        Extractor.ValidateIr(document);

        StringBuilder source = new();
        source.AppendLine("-- SPDX-FileCopyrightText: 2026 Demerzel Solutions Limited");
        source.AppendLine("-- SPDX-License-Identifier: LGPL-3.0-only");
        source.AppendLine();
        source.AppendLine("-- Generated by EnvironmentOpcodeExtractor; do not edit.");
        source.Append("-- Extractor: ").AppendLine(document.ExtractorVersion);
        source.Append("-- Semantic IR SHA-256: ").AppendLine(irHash);
        source.AppendLine();
        source.AppendLine("import Init.Data.String.Search");
        source.AppendLine("import Eip803x.Evm.Word");
        source.AppendLine("import Eip803x.Evm.MemoryStackControl");
        source.AppendLine();
        source.AppendLine("namespace Eip803x.Generated.EnvironmentOpcodeKernel");
        source.AppendLine();
        source.AppendLine("open Eip803x.Evm");
        source.AppendLine("open Eip803x.Evm.Word");
        source.AppendLine("open Eip803x.Evm.MemoryStackControl");
        source.AppendLine();
        EmitContext(source);
        EmitOpcodes(source, document.Opcodes);
        EmitTables(source, document.Opcodes);
        EmitSpecializations(source, document.Specializations);
        EmitValueSelection(source, document.Opcodes);
        EmitMachine(source);
        source.AppendLine("end Eip803x.Generated.EnvironmentOpcodeKernel");
        return Utf8WithoutBom.GetBytes(source.ToString().Replace("\r\n", "\n", StringComparison.Ordinal));
    }

    private static void EmitContext(StringBuilder source)
    {
        source.AppendLine("structure Context where");
        source.AppendLine("  executingAccount : UInt256");
        source.AppendLine("  origin : UInt256");
        source.AppendLine("  caller : UInt256");
        source.AppendLine("  callValue : UInt256");
        source.AppendLine("  calldataSize : Nat");
        source.AppendLine("  codeSize : Nat");
        source.AppendLine("  returnDataSize : Nat");
        source.AppendLine("  gasPrice : UInt256");
        source.AppendLine("  coinbase : UInt256");
        source.AppendLine("  timestamp : Nat");
        source.AppendLine("  number : Nat");
        source.AppendLine("  prevRandao : UInt256");
        source.AppendLine("  gasLimit : Nat");
        source.AppendLine("  chainId : UInt256");
        source.AppendLine("  selfBalance : UInt256");
        source.AppendLine("  baseFee : UInt256");
        source.AppendLine("  blobVersionedHashes : List UInt256");
        source.AppendLine("  excessBlobGas : Option Nat");
        source.AppendLine("  blobBaseFee : UInt256");
        source.AppendLine("  slotNumber : Option Nat");
        source.AppendLine("  blockHashes : List (Nat × UInt256)");
        source.AppendLine("  deriving Repr");
        source.AppendLine();
    }

    private static void EmitOpcodes(StringBuilder source, OpcodeDescriptor[] opcodes)
    {
        source.AppendLine("inductive Opcode where");
        foreach (OpcodeDescriptor opcode in opcodes)
            source.Append("  | ").AppendLine(opcode.Name);
        source.AppendLine("  deriving DecidableEq, Repr");
        source.AppendLine();
        source.AppendLine("def allOpcodes : List Opcode :=");
        source.Append("  [");
        for (int index = 0; index < opcodes.Length; index++)
        {
            if (index != 0)
                source.Append(", ");
            source.Append('.').Append(opcodes[index].Name);
        }
        source.AppendLine("]");
        source.AppendLine();
    }

    private static void EmitTables(StringBuilder source, OpcodeDescriptor[] opcodes)
    {
        EmitNatTable(source, "opcodeByte", opcodes, static opcode => opcode.OpcodeByte);
        EmitStringTable(source, "handlerRoute", opcodes, static opcode => opcode.HandlerRoute);
        EmitStringTable(source, "activationGate", opcodes, static opcode => opcode.ActivationGate);
        EmitNatTable(source, "fixedGas", opcodes, static opcode => checked((int)opcode.FixedGas));
        EmitNatTable(source, "dispatchStackInputs", opcodes, static opcode => opcode.DispatchStackInputs);
        EmitNatTable(source, "dispatchStackGrowth", opcodes, static opcode => opcode.DispatchStackGrowth);
        EmitNatTable(source, "semanticPops", opcodes, static opcode => opcode.SemanticPops);
        EmitNatTable(source, "semanticPushes", opcodes, static opcode => opcode.SemanticPushes);
        source.AppendLine("def checksAvailabilityBeforeGas : Opcode → Bool");
        foreach (OpcodeDescriptor opcode in opcodes)
            source.Append("  | .").Append(opcode.Name).Append(" => ").AppendLine(opcode.ChecksAvailabilityBeforeGas ? "true" : "false");
        source.AppendLine();
    }

    private static void EmitSpecializations(StringBuilder source, OpcodeSpecialization[] specializations)
    {
        source.AppendLine("inductive DispatchTable where");
        source.AppendLine("  | noTrace | noTraceCancelable | traced | tracedCancelable");
        source.AppendLine("  deriving DecidableEq, Repr");
        source.AppendLine();
        source.AppendLine("structure Specialization where");
        source.AppendLine("  opcode : Opcode");
        source.AppendLine("  table : DispatchTable");
        source.AppendLine("  tracingFlag : String");
        source.AppendLine("  cancelableFlag : String");
        source.AppendLine("  closedRoot : String");
        source.AppendLine("  deriving DecidableEq, Repr");
        source.AppendLine();
        source.AppendLine("def allDispatchTables : List DispatchTable :=");
        source.AppendLine("  [.noTrace, .noTraceCancelable, .traced, .tracedCancelable]");
        source.AppendLine();
        source.AppendLine("def tracingFlag : DispatchTable → String");
        source.AppendLine("  | .noTrace | .noTraceCancelable => \"OffFlag\"");
        source.AppendLine("  | .traced | .tracedCancelable => \"OnFlag\"");
        source.AppendLine();
        source.AppendLine("def cancelableFlag : DispatchTable → String");
        source.AppendLine("  | .noTrace | .traced => \"OffFlag\"");
        source.AppendLine("  | .noTraceCancelable | .tracedCancelable => \"OnFlag\"");
        source.AppendLine();
        source.AppendLine("def closedHandlerRoute (opcode : Opcode) (table : DispatchTable) : String :=");
        source.AppendLine("  ((handlerRoute opcode).replace \"TTracingInst\" (tracingFlag table)).replace");
        source.AppendLine("    \"TGasPolicy\" \"EthereumGasPolicy\"");
        source.AppendLine();
        source.AppendLine("def expectedClosedRoot (opcode : Opcode) (table : DispatchTable) : String :=");
        source.AppendLine("  \"VirtualMachine<EthereumGasPolicy>.ExecuteOpcode<\" ++ closedHandlerRoute opcode table ++ \",\" ++");
        source.AppendLine("    tracingFlag table ++ \",\" ++ cancelableFlag table ++ \",OnFlag>\"");
        source.AppendLine();
        source.AppendLine("def specializations : List Specialization :=");
        source.AppendLine("  [");
        for (int index = 0; index < specializations.Length; index++)
        {
            OpcodeSpecialization specialization = specializations[index];
            source.Append("    { opcode := .").Append(specialization.Opcode)
                .Append(", table := .").Append(LeanTable(specialization.DispatchTable))
                .Append(", tracingFlag := \"").Append(Escape(specialization.TracingFlag))
                .Append("\", cancelableFlag := \"").Append(Escape(specialization.CancelableFlag))
                .Append("\", closedRoot := \"").Append(Escape(specialization.ClosedRoot)).Append("\" }");
            source.AppendLine(index + 1 == specializations.Length ? string.Empty : ",");
        }
        source.AppendLine("  ]");
        source.AppendLine();
    }

    private static void EmitValueSelection(StringBuilder source, OpcodeDescriptor[] opcodes)
    {
        source.AppendLine("inductive ValueResult where");
        source.AppendLine("  | word (value : UInt256)");
        source.AppendLine("  | stackUnderflow");
        source.AppendLine("  | badInstruction");
        source.AppendLine("  deriving DecidableEq, Repr");
        source.AppendLine();
        source.AppendLine("def lookupBlockHash : Nat → List (Nat × UInt256) → Option UInt256");
        source.AppendLine("  | _, [] => none");
        source.AppendLine("  | number, (candidate, hash) :: tail =>");
        source.AppendLine("    if number = candidate then some hash else lookupBlockHash number tail");
        source.AppendLine();
        source.AppendLine("def blockHash (context : Context) (query : UInt256) : UInt256 :=");
        source.AppendLine("  if query.val < 2 ^ 64 ∧ query.val < context.number ∧ context.number ≤ query.val + 256 then");
        source.AppendLine("    (lookupBlockHash query.val context.blockHashes).getD Word.zero");
        source.AppendLine("  else Word.zero");
        source.AppendLine();
        source.AppendLine("def blobHash (context : Context) (query : UInt256) : UInt256 :=");
        source.AppendLine("  context.blobVersionedHashes[query.val]?.getD Word.zero");
        source.AppendLine();
        source.AppendLine("def value (context : Context) : Opcode → Option UInt256 → ValueResult");
        foreach (OpcodeDescriptor opcode in opcodes)
        {
            string argument = opcode.SemanticPops == 1 ? "argument" : "_argument";
            source.Append("  | .").Append(opcode.Name).Append(", ").Append(argument).Append(" => ").AppendLine(ValueExpression(opcode));
        }
        source.AppendLine();
        source.AppendLine("def contextAvailable (context : Context) : Opcode → Bool");
        foreach (OpcodeDescriptor opcode in opcodes)
        {
            string expression = opcode.Name switch
            {
                "blobbasefee" => "context.excessBlobGas.isSome",
                "slotnum" => "context.slotNumber.isSome",
                _ => "true",
            };
            source.Append("  | .").Append(opcode.Name).Append(" => ").AppendLine(expression);
        }
        source.AppendLine();
    }

    private static void EmitMachine(StringBuilder source)
    {
        source.AppendLine("structure State where");
        source.AppendLine("  gasLeft : Nat");
        source.AppendLine("  pc : Nat");
        source.AppendLine("  stack : Stack");
        source.AppendLine("  deriving Repr");
        source.AppendLine();
        source.AppendLine("inductive Status where");
        source.AppendLine("  | ok | outOfGas | stackUnderflow | stackOverflow | badInstruction");
        source.AppendLine("  deriving DecidableEq, Repr");
        source.AppendLine();
        source.AppendLine("structure Outcome where");
        source.AppendLine("  status : Status");
        source.AppendLine("  state : State");
        source.AppendLine("  deriving Repr");
        source.AppendLine();
        source.AppendLine("def withGas (state : State) (gas : Nat) : State := { state with gasLeft := gas }");
        source.AppendLine("def advancePc (state : State) : State := { state with pc := state.pc + 1 }");
        source.AppendLine();
        source.AppendLine("def applyValue (state : State) : ValueResult → Outcome");
        source.AppendLine("  | .stackUnderflow => { status := .stackUnderflow, state }");
        source.AppendLine("  | .badInstruction => { status := .badInstruction, state }");
        source.AppendLine("  | .word word =>");
        source.AppendLine("    match state.stack.push word with");
        source.AppendLine("    | some stack => { status := .ok, state := { state with stack } }");
        source.AppendLine("    | none => { status := .stackOverflow, state }");
        source.AppendLine();
        source.AppendLine("def executePaid (context : Context) (opcode : Opcode) (state : State) : Outcome :=");
        source.AppendLine("  if semanticPops opcode = 1 then");
        source.AppendLine("    match state.stack.pop with");
        source.AppendLine("    | none => { status := .stackUnderflow, state }");
        source.AppendLine("    | some (argument, stack) => applyValue { state with stack } (value context opcode (some argument))");
        source.AppendLine("  else applyValue state (value context opcode none)");
        source.AppendLine();
        source.AppendLine("def execute (context : Context) (opcode : Opcode) (state : State) : Outcome :=");
        source.AppendLine("  let advanced := advancePc state");
        source.AppendLine("  if !contextAvailable context opcode then");
        source.AppendLine("    { status := .badInstruction, state := advanced }");
        source.AppendLine("  else if fixedGas opcode ≤ advanced.gasLeft then");
        source.AppendLine("    executePaid context opcode (withGas advanced (advanced.gasLeft - fixedGas opcode))");
        source.AppendLine("  else");
        source.AppendLine("    { status := .outOfGas, state := withGas advanced 0 }");
        source.AppendLine();
        source.AppendLine("def executeAmsterdam (table : DispatchTable) (context : Context) (opcode : Opcode)");
        source.AppendLine("    (state : State) : Outcome :=");
        source.AppendLine("  match table with");
        source.AppendLine("  | .noTrace => execute context opcode state");
        source.AppendLine("  | .noTraceCancelable => execute context opcode state");
        source.AppendLine("  | .traced => execute context opcode state");
        source.AppendLine("  | .tracedCancelable => execute context opcode state");
        source.AppendLine();
    }

    private static string ValueExpression(OpcodeDescriptor opcode) => opcode.ValueSelector switch
    {
        "executingAccount" => ".word context.executingAccount",
        "origin" => ".word context.origin",
        "caller" => ".word context.caller",
        "callValue" => ".word context.callValue",
        "calldataSize" => ".word (Word.ofNat context.calldataSize)",
        "codeSize" => ".word (Word.ofNat context.codeSize)",
        "gasPrice" => ".word context.gasPrice",
        "returnDataSize" => ".word (Word.ofNat context.returnDataSize)",
        "blockHash" => "match argument with | some query => .word (blockHash context query) | none => .stackUnderflow",
        "coinbase" => ".word context.coinbase",
        "timestamp" => ".word (Word.ofNat context.timestamp)",
        "number" => ".word (Word.ofNat context.number)",
        "prevRandao" => ".word context.prevRandao",
        "gasLimit" => ".word (Word.ofNat context.gasLimit)",
        "chainId" => ".word context.chainId",
        "selfBalance" => ".word context.selfBalance",
        "baseFee" => ".word context.baseFee",
        "blobHash" => "match argument with | some query => .word (blobHash context query) | none => .stackUnderflow",
        "blobBaseFee" => "match context.excessBlobGas with | some _ => .word context.blobBaseFee | none => .badInstruction",
        "slotNumber" => "match context.slotNumber with | some slot => .word (Word.ofNat slot) | none => .badInstruction",
        _ => throw new ExtractionException($"The serialized IR has an unknown value selector '{opcode.ValueSelector}'."),
    };

    private static void EmitNatTable(StringBuilder source, string name, OpcodeDescriptor[] opcodes, Func<OpcodeDescriptor, int> selector)
    {
        source.Append("def ").Append(name).AppendLine(" : Opcode → Nat");
        foreach (OpcodeDescriptor opcode in opcodes)
            source.Append("  | .").Append(opcode.Name).Append(" => ").AppendLine(selector(opcode).ToString(CultureInfo.InvariantCulture));
        source.AppendLine();
    }

    private static void EmitStringTable(StringBuilder source, string name, OpcodeDescriptor[] opcodes, Func<OpcodeDescriptor, string> selector)
    {
        source.Append("def ").Append(name).AppendLine(" : Opcode → String");
        foreach (OpcodeDescriptor opcode in opcodes)
            source.Append("  | .").Append(opcode.Name).Append(" => \"").Append(Escape(selector(opcode))).AppendLine("\"");
        source.AppendLine();
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

    private static string LeanTable(string table) => table switch
    {
        "NoTrace" => "noTrace",
        "NoTraceCancelable" => "noTraceCancelable",
        "Traced" => "traced",
        "TracedCancelable" => "tracedCancelable",
        _ => throw new ExtractionException($"The serialized IR has an unknown dispatch table '{table}'."),
    };
}
