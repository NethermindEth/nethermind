    [Test]
    public void Generated_Lean_is_theorem_free_and_exposes_the_five_field_fold()
    {
        string root = FindRepoRoot();
        string generated = File.ReadAllText(Path.Combine(root, "tools/Evm/Lean/AuthorizationStateGasFoldExtractor/Generated/AuthorizationStateGasFold.lean"));
        string ir = File.ReadAllText(Path.Combine(root, "tools/Evm/Lean/AuthorizationStateGasFoldExtractor/Generated/AuthorizationStateGasFold.ir.json"));
        string extractorVersion = JsonNode.Parse(ir)!["extractorVersion"]!.GetValue<string>();

        using (Assert.EnterMultipleScope())
        {
            Assert.That(generated, Does.StartWith($"-- Generated by AuthorizationStateGasFoldExtractor {extractorVersion}."));
            Assert.That(generated, Does.Not.Contain("theorem "));
            Assert.That(generated, Does.Not.Contain("eip8038"));
            Assert.That(generated, Does.Contain("def foldTopFrameStateGas"));
            Assert.That(generated, Does.Contain("def stateChargeSpill"));
            Assert.That(generated, Does.Contain(
                "if available.value < amount then none else some { available with value := available.value - amount }"));
            Assert.That(generated, Does.Contain("def callerVisible"));
            Assert.That(generated, Does.Contain("stateGasSpillRefunded"));
            Assert.That(generated, Does.Contain("logicalAccountExists : Bool"));
            Assert.That(generated, Does.Not.Contain("\n  accountExists : Bool"));
            Assert.That(ir, Does.Contain("externalObligations"));
            Assert.That(ir, Does.Contain("stateChargeAdapter"));
            Assert.That(ir, Does.Contain("ConsumeRaw(refgas,gasCost)"));
            Assert.That(ir, Does.Contain("complete production authorization loop"));
        }
    }

