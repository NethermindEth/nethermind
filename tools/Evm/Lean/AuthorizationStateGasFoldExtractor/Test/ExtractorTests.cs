    private static void AssertSourceMutationRejected(string relativePath, Func<string, string> mutation)
    {
        string root = FindRepoRoot();
        using TemporaryDirectory fixture = new();
        CopyFixture(root, fixture.Path);
        string path = Path.Combine(fixture.Path, relativePath.Replace('/', Path.DirectorySeparatorChar));
        string original = File.ReadAllText(path);
        string changed = mutation(original);
        Assert.That(changed, Is.Not.EqualTo(original), "Mutation did not change its fixture source.");
        File.WriteAllText(path, changed, new UTF8Encoding(false));
        using TemporaryDirectory output = new();
        Assert.Throws<ExtractionException>(() => Extractor.Extract(fixture.Path, output.Path, Path.Combine(output.Path, "fold.lean")));
    }

    private static void AssertFixtureMutationRejected(string root, string relativePath, Func<string, string> mutation)
    {
        using TemporaryDirectory fixture = new();
        CopyFixture(root, fixture.Path);
        string path = Path.Combine(fixture.Path, relativePath.Replace('/', Path.DirectorySeparatorChar));
        string original = File.ReadAllText(path);
        string changed = mutation(original);
        Assert.That(changed, Is.Not.EqualTo(original), "Mutation did not change its fixture artifact.");
