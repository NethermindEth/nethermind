using System.Text;

namespace Nethermind.Evm.Lean.TransientStorageOpcodeExtractor;

internal static class LeanEmitter
{
    private static readonly UTF8Encoding Utf8WithoutBom = new(false);

    internal static byte[] Emit(IrDocument document, string irHash)
    {
        Validate(document);
        OpcodeDescriptor tload = document.Opcodes.Single(static opcode => opcode.Name == "tload");
        OpcodeDescriptor tstore = document.Opcodes.Single(static opcode => opcode.Name == "tstore");
        string specializationEntries = string.Join(",\n  ", document.Specializations.Select(static specialization =>
            $"{{ opcode := .{specialization.Opcode}, table := {LeanString(specialization.Table)}, " +
            $"tracingFlag := {LeanString(specialization.TracingFlag)}, cancellationFlag := {LeanString(specialization.CancellationFlag)}, " +
            $"closedRoot := {LeanString(specialization.ClosedRoot)} }}"));

        string source = $$"""
            -- SPDX-FileCopyrightText: 2026 Demerzel Solutions Limited
            -- SPDX-License-Identifier: LGPL-3.0-only

            -- Generated by TransientStorageOpcodeExtractor; do not edit.
            -- Extractor: {{document.ExtractorVersion}}
            -- Semantic IR SHA-256: {{irHash}}

            import Eip803x.Gas
            import Eip803x.Evm.MemoryStackControl
            import Eip803x.Evm.Word

            namespace Eip803x.Generated.TransientStorageOpcodeKernel

            open Eip803x
            open Eip803x.GasMachine
            open Eip803x.Evm
            open Eip803x.Evm.MemoryStackControl
            open Eip803x.Evm.Word

            structure Schedule where
              warmAccess : Nat
              deriving DecidableEq, Repr

            def amsterdamSchedule : Schedule := { warmAccess := {{tload.FixedGas}} }

            inductive Opcode where
              | tload
              | tstore
              deriving DecidableEq, Repr

            def allOpcodes : List Opcode := [.tload, .tstore]

            def opcodeByte : Opcode → Nat
              | .tload => {{tload.OpcodeByte}}
              | .tstore => {{tstore.OpcodeByte}}

            structure DispatchSpecialization where
              opcode : Opcode
              table : String
              tracingFlag : String
              cancellationFlag : String
              closedRoot : String
              deriving DecidableEq, Repr

            def dispatchSpecializations : List DispatchSpecialization :=
              [{{specializationEntries}}]

            def fixedGas (schedule : Schedule) : Opcode → Nat
              | .tload => schedule.warmAccess
              | .tstore => schedule.warmAccess

            structure Cell where
              address : UInt256
              key : UInt256
              deriving DecidableEq, Repr

            abbrev Store := List (Cell × UInt256)

            def read : Store → Cell → UInt256
              | [], _ => Word.zero
              | (candidate, value) :: tail, cell =>
                  if candidate = cell then value else read tail cell

            def write : Store → Cell → UInt256 → Store
              | [], cell, value => [(cell, value)]
              | (candidate, current) :: tail, cell, value =>
                  if candidate = cell then
                    (cell, value) :: tail
                  else
                    (candidate, current) :: write tail cell value

            structure Frame where
              checkpoint : Store
              current : Store
              deriving Repr

            def load (frame : Frame) (address key : UInt256) : UInt256 :=
              read frame.current ⟨address, key⟩

            def store (frame : Frame) (address key value : UInt256) : Frame :=
              { frame with current := write frame.current ⟨address, key⟩ value }

            structure MachineState where
              gas : GasState
              stack : Stack
              transient : Frame
              pc : Nat
              deriving Repr

            inductive Status where
              | ok
              | outOfGas
              | stackUnderflow
              | stackOverflow
              | staticCallViolation
              | badInstruction
              deriving DecidableEq, Repr

            structure Outcome where
              status : Status
              state : MachineState
              deriving Repr

            def withGas (state : MachineState) (gas : GasState) : MachineState :=
              { state with gas }

            def exhaustExecutionGas (state : MachineState) : MachineState :=
              { state with gas := { state.gas with gasLeft := 0 } }

            def advancePc (state : MachineState) : MachineState :=
              { state with pc := state.pc + 1 }

            def executeTLoad (schedule : Schedule) (address : UInt256) (state : MachineState) : Outcome :=
              let entered := advancePc state
              match chargeExecution schedule.warmAccess entered.gas with
              | .error _ => { status := .outOfGas, state := exhaustExecutionGas entered }
              | .ok gasAfter =>
                let charged := withGas entered gasAfter
                match entered.stack.pop with
                | none => { status := .stackUnderflow, state := charged }
                | some (key, tail) =>
                  let value := load entered.transient address key
                  match tail.push value with
                  | none => { status := .stackOverflow, state := { charged with stack := tail } }
                  | some stackAfter => { status := .ok, state := { charged with stack := stackAfter } }

            def executeTStore (schedule : Schedule) (isStatic : Bool) (address : UInt256)
                (state : MachineState) : Outcome :=
              let entered := advancePc state
              if isStatic then
                { status := .staticCallViolation, state := entered }
              else
                match chargeExecution schedule.warmAccess entered.gas with
                | .error _ => { status := .outOfGas, state := exhaustExecutionGas entered }
                | .ok gasAfter =>
                  let charged := withGas entered gasAfter
                  match entered.stack.pop with
                  | none => { status := .stackUnderflow, state := charged }
                  | some (key, afterKey) =>
                    match afterKey.pop with
                    | none => { status := .stackUnderflow, state := { charged with stack := afterKey } }
                    | some (value, stackAfter) =>
                      { status := .ok
                        state :=
                          { charged with
                            stack := stackAfter
                            transient := store entered.transient address key value } }

            def execute (schedule : Schedule) (enabled isStatic : Bool) (address : UInt256)
                (opcode : Nat) (state : MachineState) : Outcome :=
              if !enabled then
                { status := .badInstruction, state := advancePc state }
              else if opcode = opcodeByte .tload then
                executeTLoad schedule address state
              else if opcode = opcodeByte .tstore then
                executeTStore schedule isStatic address state
              else
                { status := .badInstruction, state := advancePc state }

            end Eip803x.Generated.TransientStorageOpcodeKernel
            """;

        return Utf8WithoutBom.GetBytes(source.Replace("\r\n", "\n", StringComparison.Ordinal));
    }

    internal static void Validate(IrDocument document)
    {
        if (document is null || document.Reachability is null || document.Opcodes is null ||
            document.Specializations is null || document.OpenExtractionObligations is null ||
            document.Reachability.Service is null || document.Reachability.ConcreteVm is null ||
            document.Reachability.ClosedVm is null || document.Reachability.GasPolicy is null ||
            document.Reachability.Fork is null || document.Reachability.Activation is null ||
            document.Reachability.BuildSelection is null || document.Reachability.DispatchRoot is null ||
            document.Opcodes.Any(static opcode => opcode is null || opcode.Name is null ||
                opcode.Instruction is null || opcode.Handler is null || opcode.Wrapper is null ||
                opcode.OrderedEffects is null || opcode.OrderedEffects.Any(static effect => effect is null)) ||
            document.Specializations.Any(static specialization => specialization is null ||
                specialization.Opcode is null || specialization.Table is null ||
                specialization.TracingFlag is null || specialization.CancellationFlag is null ||
                specialization.ClosedRoot is null) ||
            document.OpenExtractionObligations.Any(static obligation => obligation is null))
            throw new ExtractionException("The round-tripped transient-storage IR contains null collections, entries, or fields.");

        if (document.SchemaVersion != 1 || document.ExtractorVersion != "1.0.0" ||
            document.Kernel != "Nethermind standard-mainnet Amsterdam TLOAD/TSTORE immediate-handler slice" ||
            document.Opcodes.Length != 2 || document.Specializations.Length != 8)
            throw new ExtractionException("The round-tripped transient-storage IR has an unsupported shape.");

        ReachabilityDescriptor expectedReachability = new(
            "IVirtualMachine",
            "EthereumVirtualMachine",
            "VirtualMachine<EthereumGasPolicy>",
            "EthereumGasPolicy",
            "Amsterdam",
            "Cancun.IsEip1153Enabled inherited through the complete named-mainnet ancestry",
            "Directory.Build.targets selects *.std.cs when EnableZkEvm != true",
            "VirtualMachine<EthereumGasPolicy>.ExecuteOpcode");
        if (document.Reachability != expectedReachability)
            throw new ExtractionException("The serialized IR contains an unsupported standard-mainnet reachability root.");

        HashSet<string> names = new(StringComparer.Ordinal);
        HashSet<int> bytes = [];
        foreach (OpcodeDescriptor opcode in document.Opcodes)
        {
            if (!names.Add(opcode.Name) || !bytes.Add(opcode.OpcodeByte) || opcode.OpcodeByte is < 0 or > byte.MaxValue)
                throw new ExtractionException("The serialized IR contains a duplicate or out-of-range transient-storage opcode.");
            string[] expectedEffects;
            if (opcode.Name == "tload")
            {
                if (opcode.Instruction != "TLOAD" || opcode.OpcodeByte != 0x5c ||
                    opcode.Handler != "TLoadOpcode<TTracingInst>" ||
                    opcode.Wrapper != "EvmInstructions.InstructionTLoad<TGasPolicy,TTracingInst>" ||
                    opcode.FixedGas != 100 || opcode.StackInputs != 1 || opcode.StackOutputs != 1 ||
                    opcode.StaticCheckBeforeGas)
                    throw new ExtractionException("The serialized IR contains an unsupported tload descriptor.");
                expectedEffects = ["charge", "popKey", "readExecutingAccountCell", "pushValue"];
            }
            else if (opcode.Name == "tstore")
            {
                if (opcode.Instruction != "TSTORE" || opcode.OpcodeByte != 0x5d ||
                    opcode.Handler != "TStoreOpcode" ||
                    opcode.Wrapper != "EvmInstructions.InstructionTStore<TGasPolicy>" ||
                    opcode.FixedGas != 100 || opcode.StackInputs != 2 || opcode.StackOutputs != 0 ||
                    !opcode.StaticCheckBeforeGas)
                    throw new ExtractionException("The serialized IR contains an unsupported tstore descriptor.");
                expectedEffects = ["staticCheck", "charge", "popKey", "popValue", "snapshotPreWriteValueWhenTracing", "write"];
            }
            else
            {
                throw new ExtractionException($"The serialized IR contains unsupported opcode {opcode.Name}.");
            }

            if (!opcode.OrderedEffects.SequenceEqual(expectedEffects, StringComparer.Ordinal))
                throw new ExtractionException($"The serialized IR contains unsupported {opcode.Name} effect ordering.");
        }
        if (!document.Opcodes.Select(static opcode => opcode.Name)
                .SequenceEqual(["tload", "tstore"], StringComparer.Ordinal))
            throw new ExtractionException("The serialized IR opcode descriptor order changed.");

        DispatchSpecialization[] expectedSpecializations =
        [
            ExpectedSpecialization("tload", "NoTrace", "OffFlag", "OffFlag", "TLoadOpcode<OffFlag>"),
            ExpectedSpecialization("tstore", "NoTrace", "OffFlag", "OffFlag", "TStoreOpcode"),
            ExpectedSpecialization("tload", "NoTraceCancelable", "OffFlag", "OnFlag", "TLoadOpcode<OffFlag>"),
            ExpectedSpecialization("tstore", "NoTraceCancelable", "OffFlag", "OnFlag", "TStoreOpcode"),
            ExpectedSpecialization("tload", "Traced", "OnFlag", "OffFlag", "TLoadOpcode<OnFlag>"),
            ExpectedSpecialization("tstore", "Traced", "OnFlag", "OffFlag", "TStoreOpcode"),
            ExpectedSpecialization("tload", "TracedCancelable", "OnFlag", "OnFlag", "TLoadOpcode<OnFlag>"),
            ExpectedSpecialization("tstore", "TracedCancelable", "OnFlag", "OnFlag", "TStoreOpcode"),
        ];
        HashSet<(string Opcode, string Table)> keys = [];
        foreach (DispatchSpecialization specialization in document.Specializations)
        {
            if (!keys.Add((specialization.Opcode, specialization.Table)))
                throw new ExtractionException($"The serialized IR duplicates dispatch key {specialization.Opcode}/{specialization.Table}.");
            if (specialization.ClosedRoot.Contains("/", StringComparison.Ordinal))
                throw new ExtractionException("The serialized IR contains a placeholder dispatch root.");
        }
        if (!document.Specializations.SequenceEqual(expectedSpecializations))
            throw new ExtractionException("The serialized IR does not contain the eight exact TLOAD/TSTORE dispatch specializations.");

        string[] expectedObligations =
        [
            "Theorems cover the immediate TLOAD/TSTORE transition selected by standard-mainnet Amsterdam dispatch; C# language, Roslyn binding, CLR/JIT, unsafe function-pointer dispatch, and hardware correctness remain outside the theorem.",
            "UInt256 and Address representation, EvmStack unsafe storage and endian conversions, ReadOnlySpan lifetime, zero-value byte canonicalization, and PushBytes/PopUInt256/PopWord256 implementation equivalence remain adapter premises.",
            "IWorldState transient-provider lookup, journaling, nested-frame snapshot restore/merge, account destruction, transaction-boundary ResetTransient, and WorldState decorator behavior remain separate production-refinement obligations.",
            "Tracer callback behavior, callback exceptions, trace byte representation, cancellation, opcode-count accounting, and instruction trace side effects are outside the consensus-state refinement; the admitted handler preserves the fixed pre-write TSTORE trace ordering.",
        ];
        if (!document.OpenExtractionObligations.SequenceEqual(expectedObligations, StringComparer.Ordinal))
            throw new ExtractionException("The serialized IR extraction obligations changed.");
    }

    private static DispatchSpecialization ExpectedSpecialization(
        string opcode,
        string table,
        string tracing,
        string cancellation,
        string handler) =>
        new(opcode, table, tracing, cancellation,
            $"VirtualMachine<EthereumGasPolicy>.ExecuteOpcode<{handler},{tracing},{cancellation},OnFlag>");

    private static string LeanString(string value) =>
        $"\"{value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)}\"";
}
